"""
Генерація короткої анотації та оцінки рівня доказовості для статті через Claude API.

ВАЖЛИВО щодо авторського права: модель отримує лише офіційну анотацію (abstract) статті
з PubMed і має ПЕРЕФРАЗУВАТИ її власними словами, а не копіювати. Повний текст статей
ніде не використовується. Кожна анотація в боті супроводжується посиланням на оригінал.

Шкала доказовості — проста, власна (High / Medium / Low), а не формальна GRADE/Oxford CEBM:
  HIGH   — систематичні огляди, мета-аналізи, РКД (рандомізовані контрольовані дослідження),
           офіційні рекомендації асоціацій (EFSUMB/AIUM/ESR/ACR тощо)
  MEDIUM — проспективні когортні дослідження, великі ретроспективні серії з чіткою методологією
  LOW    — описи випадків (case report/series), малі ретроспективні вибірки, пілотні/попередні
           дослідження, думка експертів, редакційні статті

Це навмисно спрощена шкала для швидкої орієнтації лікаря в стрічці, а не заміна повноцінного
критичного аналізу першоджерела.
"""

import json
import os

from anthropic import Anthropic

MODEL = "claude-sonnet-5"  # за потреби зменшити витрати — можна замінити на claude-haiku-4-5-20251001

SYSTEM_PROMPT = """Ти — асистент, який готує короткі анотації наукових статей з ультразвукової
діагностики (УЗД) для лікарів-практиків УЗД-діагностики в Україні.

Правила:
1. Пиши українською мовою, професійним, стислим стилем "лікар для лікаря".
2. НІКОЛИ не копіюй речення з анотації дослівно — формулюй власними словами.
3. Відповідай ЛИШЕ у форматі JSON, без жодного тексту до чи після, без markdown-огорожі.
4. Поле "evidence_level" — лише одне з трьох значень: "High", "Medium", "Low".
5. Оцінюй рівень доказовості за дизайном дослідження, який згаданий в анотації:
   - High: систематичний огляд, мета-аналіз, РКД (randomized controlled trial), офіційна
     рекомендація/консенсус асоціації.
   - Medium: проспективне когортне дослідження, велика ретроспективна серія з чіткою методологією.
   - Low: опис випадку/серія випадків, мала ретроспективна вибірка, пілотне дослідження,
     думка експертів, редакційна стаття, або якщо дизайн дослідження неможливо визначити.
6. Якщо в анотації є конкретні цифри ефективності методу (чутливість, специфічність, AUC,
   точність тощо) — обов'язково включи їх у summary.

Формат відповіді (валідний JSON):
{
  "summary": "3-5 речень українською: що досліджували, головний результат, практичний висновок для УЗД-лікаря",
  "evidence_level": "High" | "Medium" | "Low",
  "evidence_reason": "Одне речення — чому саме такий рівень (який дизайн дослідження)"
}
"""


def summarize_article(title: str, abstract: str, journal: str) -> dict:
    """Повертає dict {summary, evidence_level, evidence_reason}. При помилці — безпечний fallback."""
    client = Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])

    user_content = (
        f"Назва статті: {title}\n"
        f"Журнал: {journal}\n"
        f"Офіційна анотація (abstract):\n{abstract}"
    )

    try:
        response = client.messages.create(
            model=MODEL,
            max_tokens=600,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_content}],
        )
        raw_text = "".join(
            block.text for block in response.content if block.type == "text"
        ).strip()

        # про всяк випадок прибираємо можливі ```json огорожі
        raw_text = raw_text.removeprefix("```json").removeprefix("```").removesuffix("```").strip()

        parsed = json.loads(raw_text)
        level = parsed.get("evidence_level", "Low")
        if level not in ("High", "Medium", "Low"):
            level = "Low"

        return {
            "summary": parsed.get("summary", "Не вдалося сформувати анотацію."),
            "evidence_level": level,
            "evidence_reason": parsed.get("evidence_reason", ""),
        }

    except Exception as e:  # noqa: BLE001 — навмисно широкий except для стабільності пайплайну
        return {
            "summary": f"⚠️ Не вдалося автоматично згенерувати анотацію ({e}). Див. оригінал за посиланням.",
            "evidence_level": "Low",
            "evidence_reason": "оцінку не вдалося виконати автоматично",
        }
